def img(rows):
    h, w = len(rows), max(len(r) for r in rows)
    im = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            c = P.get(ch)
            if c: im.putpixel((x, y), c if len(c) == 4 else c + (255,))
    return im
def save(name, rows):
    img(rows).save(f'{OUT}/{name}.png')

