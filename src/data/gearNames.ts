/** 장(1~)의 몬스터·보스 이름 → 이름 재료 (「정예 · 」 떼고 · 보스는 「」 안 별명) */
export function chapterFrom(c: number, boss: boolean): string[] {
  const m = CHAPTER_MOBS[(c - 1) % CHAPTER_MOBS.length];
  if (boss) return [m.boss.match(/「(.+?)」/)?.[0] ?? m.boss];
  return Object.values(m.names).map((n) => n.replace(/^정예 · /, ''));
}
